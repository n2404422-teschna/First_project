# Список цін товарів у кошику
prices = [250, 480, 199, 322]
total = 0

# Обчислюємо загальну суму за допомогою циклу for
for price in prices:
    total = total + price

# Перевіряємо умову безкоштовної доставки
if total >= 1000:
    print("Безкоштовна доставка")
else:
    print("Не вистачає до 1000:", 1000 - total)