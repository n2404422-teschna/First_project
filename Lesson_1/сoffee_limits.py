# Контроль випитої кількості кави в день (не більше 3 в день)
kavas = [1, 1, 1, 1]
total = 0
# Обчислюємо загальну суму за допомогою циклу for
for kava in kavas:
    total = total + kava
# Перевіряємо умову випитої в день кави
if total >= 3:
    print("Каву пити будемо вже завтра, зайчику)))")
else:
    print("Ще можеш йти пити каву. Не вистачає до 3:", 3 - total)
